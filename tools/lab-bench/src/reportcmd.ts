/**
 * The `report` command: turn a run directory's results.json into a local
 * HTML + Markdown report (aggregate tables only — never image bytes, never a
 * person's image; the file names in the manifest are ids and transforms).
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { readResults } from "./runs.ts";
import type { MatchResults } from "./matching.ts";
import type { DetectResults } from "./detectcmd.ts";
import { PROBE_TRANSFORMS } from "./setformat.ts";

const pct = (x: number | null | undefined): string => (x === null || x === undefined ? "—" : `${(100 * x).toFixed(1)}%`);
const num = (x: number | null | undefined, digits = 2): string => (x === null || x === undefined ? "—" : x.toFixed(digits));

export function renderMarkdown(results: MatchResults | DetectResults): string {
  const lines: string[] = [];
  lines.push(`# E1 bench report — ${results.kind}`, "");
  lines.push(`- created: ${results.createdAt}`);
  const setBits = [`${results.set.items} items`];
  if (results.set.gallery !== undefined) setBits.push(`${results.set.gallery} gallery`);
  if ((results as MatchResults).set.probes !== undefined) setBits.push(`${(results as MatchResults).set.probes} probes`);
  lines.push(`- set: ${results.set.dir} (${setBits.join(", ")})`);
  lines.push("");
  if (results.kind === "match") {
    lines.push(`Recall at a ${(results.config.targetFmr * 100).toFixed(1)}% false-match rate, per transform. Thresholds are calibrated per transform on the impostor pairs (probe vs unrelated originals, plus the gallery noise floor).`, "");
    const methods = Object.entries(results.methods);
    lines.push("| transform | " + methods.map(([id]) => id).join(" | ") + " |");
    lines.push("|---|" + methods.map(() => "---").join("|") + "|");
    for (const t of PROBE_TRANSFORMS) {
      if ((results.set.perTransform[t] ?? 0) === 0) continue;
      lines.push(`| ${t} | ` + methods.map(([, m]) => (m.available ? pct(m.perTransform[t]?.recall ?? null) : "skipped")).join(" | ") + " |");
    }
    lines.push("");
    lines.push("Thresholds at the operating points:", "");
    lines.push("| transform | " + methods.map(([id]) => id).join(" | ") + " |");
    lines.push("|---|" + methods.map(() => "---").join("|") + "|");
    for (const t of PROBE_TRANSFORMS) {
      if ((results.set.perTransform[t] ?? 0) === 0) continue;
      lines.push(`| ${t} | ` + methods.map(([, m]) => (m.available ? num(m.perTransform[t]?.threshold ?? null, 2) : "—")).join(" | ") + " |");
    }
    lines.push("");
    for (const [id, m] of methods) {
      if (m.available) continue;
      lines.push(`- ${id}: skipped — ${m.reason}`);
    }
    for (const note of results.notes) lines.push(`- note: ${note}`);
  } else {
    lines.push("Accuracy and AUC per detector and per transform. AUC pools the transform's items with the untouched originals; it is blank where a pool has a single class.", "");
    lines.push("| detector | transform | n | accuracy | AUC | mean fake | mean real | errors |");
    lines.push("|---|---|---|---|---|---|---|---|");
    for (const d of results.detectors) {
      for (const [t, stat] of Object.entries(d.perTransform)) {
        lines.push(`| ${d.id} | ${t} | ${stat.n} | ${pct(stat.accuracy)} | ${pct(stat.auc)} | ${num(stat.meanScoreFake, 3)} | ${num(stat.meanScoreReal, 3)} | ${stat.errors} |`);
      }
      lines.push(`| ${d.id} | **overall** | ${d.items} | ${pct(d.overallAccuracy)} | — | — | — | ${d.errors} |`);
    }
    for (const s of results.skipped) lines.push(`- ${s.id}: skipped — ${s.reason}`);
  }
  lines.push("");
  lines.push("Generated by tools/lab-bench (`report`). Aggregate numbers only; per-pair and per-item scores live beside this file in results.json.");
  return lines.join("\n");
}

function escapeHtml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

export function renderHtml(results: MatchResults | DetectResults): string {
  const md = renderMarkdown(results);
  // The Markdown renderer here is intentionally tiny: headings, bullets and
  // tables, nothing else. No external assets, no scripts.
  const lines = md.split("\n");
  const out: string[] = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i]!;
    if (line.startsWith("|")) {
      const rows: string[][] = [];
      while (i < lines.length && lines[i]!.startsWith("|")) {
        const cells = lines[i]!.split("|").slice(1, -1).map((c) => c.trim());
        // Drop the |---|---| separator rows.
        if (!cells.every((c) => /^:?-+:?$/.test(c))) rows.push(cells);
        i++;
      }
      out.push("<table>");
      rows.forEach((cells, idx) => {
        out.push(
          `<tr>${cells.map((c) => `<td${idx === 0 ? ' style="font-weight:600;background:#f4f4f4"' : ""}>${escapeHtml(c)}</td>`).join("")}</tr>`,
        );
      });
      out.push("</table>");
      continue;
    }
    if (line.startsWith("# ")) out.push(`<h1>${escapeHtml(line.slice(2))}</h1>`);
    else if (line.startsWith("- ")) out.push(`<li>${escapeHtml(line.slice(2))}</li>`);
    else if (line !== "") out.push(`<p>${escapeHtml(line)}</p>`);
    i++;
  }
  return `<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><title>E1 bench report — ${escapeHtml(results.kind)}</title>
<style>
body{font-family:system-ui,sans-serif;max-width:60rem;margin:2rem auto;padding:0 1rem;color:#1a1a1a}
table{border-collapse:collapse;margin:0.5rem 0}
td{border:1px solid #d0d0d0;padding:0.25rem 0.6rem}
li{margin:0.2rem 0 0.2rem 1.2rem}
</style></head>
<body>
${out.join("\n")}
</body></html>
`;
}

export function runReport(runDir: string): { markdown: string; html: string; dir: string } {
  const results = readResults(runDir) as MatchResults | DetectResults;
  if (results.kind !== "match" && results.kind !== "detect") throw new Error(`unknown results kind in ${runDir}`);
  const markdown = renderMarkdown(results);
  const html = renderHtml(results);
  writeFileSync(join(runDir, "report.md"), `${markdown}\n`);
  writeFileSync(join(runDir, "report.html"), `${html}\n`);
  return { markdown, html, dir: runDir };
}
