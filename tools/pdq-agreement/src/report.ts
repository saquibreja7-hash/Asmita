import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { hammingDistance, PDQ_MATCH_THRESHOLD } from "../../../asmita/src/lib/pdq/pdq";
import { generateFixtures } from "./fixtures";
import { FAIL_ON, recipeSharpVersions } from "./prepare";
import { nodeBaselineHash, nodePreparedHash } from "./node-pipeline";
import { browserHashes } from "./browser-pipeline";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

const stats = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  const pct = (p: number) => s[Math.min(s.length - 1, Math.ceil(p * s.length) - 1)];
  return { n: s.length, max: s[s.length - 1], p99: pct(0.99), p95: pct(0.95), median: pct(0.5), mean: xs.reduce((a, b) => a + b, 0) / xs.length };
};
const f1 = (x: number) => x.toFixed(1);

async function main() {
  const fixtures = await generateFixtures();
  console.log(`Generated ${fixtures.length} fixtures`);
  const { results: br, userAgent } = await browserHashes(fixtures);

  type Row = {
    name: string; cls: string; dims: string; browserDims?: string; bytes: number;
    b?: { hash: string; quality: number }; base: { hash: string; quality: number }; prep: { hash: string; quality: number };
    dBase?: number; dPrep?: number; error?: string;
  };
  const rows: Row[] = [];
  for (const f of fixtures) {
    const base = await nodeBaselineHash(f.buffer);
    const prep = await nodePreparedHash(f.buffer);
    const b = br.get(f.name);
    const row: Row = {
      name: f.name, cls: f.cls, bytes: f.buffer.length, dims: `${prep.width}x${prep.height}`,
      base, prep,
    };
    if (b?.hash) {
      row.b = { hash: b.hash, quality: b.quality! };
      row.dBase = hammingDistance(base.hash, b.hash);
      row.dPrep = hammingDistance(prep.hash, b.hash);
    } else row.error = b?.error ?? "missing";
    rows.push(row);
  }
  const ok = rows.filter((r) => r.b);
  const failed = rows.filter((r) => !r.b);

  const L: string[] = [];
  const w = (s = "") => L.push(s);
  const sBase = stats(ok.map((r) => r.dBase!));
  const sPrep = stats(ok.map((r) => r.dPrep!));

  w("# PDQ agreement report: Node (sharp + pdq.ts) vs browser (SubmitForm path)");
  w();
  const recipe = recipeSharpVersions();
  w(`Generated by \`npm run report\` in tools/pdq-agreement. Browser: ${userAgent}. node-prepared: crawler/src/prepare.ts (imported, not copied) with the crawler's sharp ${recipe.sharp}, libvips ${recipe.vips}, failOn "${FAIL_ON}". node-baseline: the harness's sharp ${sharp.versions.sharp}, libvips ${sharp.versions.vips}.`);
  w(`Fixtures: ${fixtures.length} synthetic non-intimate images (${failed.length} failed in the browser). Match threshold: ${PDQ_MATCH_THRESHOLD}. Meta's cross-pipeline agreement guidance: about 10.`);
  w();
  w("Pipelines: **browser** = createImageBitmap(file) -> full-size canvas -> getImageData -> computePdqHash (verbatim copy of `hashImageFile`, source-sync tested). **node-baseline** = sharp `.rotate().ensureAlpha().raw()` -> computePdqHash. **node-prepared** = `prepareForPdq()` from crawler/src/prepare.ts, the crawler's own module (adds sRGB conversion and canvas alpha emulation).");
  w();
  w("## Summary: Node vs browser Hamming distance");
  w();
  w("| pipeline | n | max | p99 | p95 | median | mean | exact matches |");
  w("|---|---|---|---|---|---|---|---|");
  for (const [label, key, s] of [["node-baseline", "dBase", sBase], ["node-prepared", "dPrep", sPrep]] as const)
    w(`| ${label} | ${s.n} | ${s.max} | ${s.p99} | ${s.p95} | ${s.median} | ${f1(s.mean)} | ${ok.filter((r) => r[key] === 0).length} |`);
  w();
  if (failed.length) {
    w("### Browser failures");
    for (const r of failed) w(`- ${r.name}: ${r.error}`);
    w();
  }
  w("## Per image");
  w();
  w("| image | class | dims (post-orientation) | Q browser | Q node-prep | d baseline | d prepared |");
  w("|---|---|---|---|---|---|---|");
  for (const r of rows)
    w(`| ${r.name} | ${r.cls} | ${r.dims} | ${r.b?.quality ?? "n/a"} | ${r.prep.quality} | ${r.dBase ?? "n/a"} | ${r.dPrep ?? "n/a"} |`);
  w();

  w("## Which classes disagree most (node-prepared vs browser)");
  w();
  w("| class | n | max | mean | max (baseline) | mean (baseline) |");
  w("|---|---|---|---|---|---|");
  const classes = [...new Set(ok.map((r) => r.cls))];
  const byClass = classes.map((c) => {
    const xs = ok.filter((r) => r.cls === c);
    const p = stats(xs.map((r) => r.dPrep!)), q = stats(xs.map((r) => r.dBase!));
    return { c, n: xs.length, p, q };
  }).sort((a, b) => b.p.max - a.p.max || b.p.mean - a.p.mean);
  for (const x of byClass) w(`| ${x.c} | ${x.n} | ${x.p.max} | ${f1(x.p.mean)} | ${x.q.max} | ${f1(x.q.mean)} |`);
  w();

  const over = ok.filter((r) => r.dPrep! > 10).sort((x, y) => y.dPrep! - x.dPrep!);
  const exceptionClasses = [...new Set(over.map((r) => r.cls))];
  const go = failed.length === 0 && over.length === 0;
  const worst = [...ok].sort((a, b) => b.dPrep! - a.dPrep!)[0];
  w("## Verdict");
  w();
  w(`### ${go ? "GO" : exceptionClasses.length ? "GO with exceptions" : "NO-GO"}: Node + sharp with pdq.ts for the crawler`);
  w();
  w(`Basis: Node-vs-browser distance for the SAME file (node-prepared), not original-vs-transformed distances. Rule: GO if every class that matters (JPEG/PNG/WebP in RGB, greyscale, alpha, palette, EXIF-rotated, all sizes, CMYK) agrees within 10; classes above 10 are listed as exceptions.`);
  w();
  w(`- Max **${sPrep.max}** (${worst.name}), p99 ${sPrep.p99}, p95 ${sPrep.p95}, mean ${f1(sPrep.mean)}; exact matches ${ok.filter((r) => r.dPrep === 0).length}/${ok.length}. Margin from the worst image to the ${PDQ_MATCH_THRESHOLD} match threshold: ${PDQ_MATCH_THRESHOLD - sPrep.max} bits. Baseline recipe max: ${sBase.max}.`);
  w(`- Images above 10: ${over.length ? over.map((r) => `${r.name} (${r.cls}, ${r.dPrep})`).join("; ") : "none"}.`);
  const nonzero = ok.filter((r) => r.dPrep! > 0).sort((x, y) => y.dPrep! - x.dPrep!);
  w(`- Every image with non-zero distance: ${nonzero.map((r) => `${r.name} (${r.cls}, ${r.dPrep})`).join("; ") || "none"}.`);
  if (exceptionClasses.length) {
    w("- **Exceptions:**");
    for (const c of exceptionClasses) w(`  - ${c}: max ${Math.max(...over.filter((r) => r.cls === c).map((r) => r.dPrep!))} bits. Recommendation: crawler should skip this class or accept reduced recall.`);
  } else {
    w("- Exceptions: none on this synthetic set. Known unsupported or weak spots are in the caveats below.");
  }
  if (failed.length) w(`- ${failed.length} fixture(s) failed to decode in the browser and are excluded; see Browser failures.`);
  w();
  w("### Decode settings the crawler must use");
  w();
  w("The crawler uses `prepareForPdq()` in crawler/src/prepare.ts, which this report measures directly. It is:");
  w();
  w("```ts");
  w(`sharp(buffer, { failOn: '${FAIL_ON}', limitInputPixels: 25_000_000, animated: false })`);
  w("  .rotate()                 // apply EXIF orientation (browser: imageOrientation 'from-image' is the default)");
  w("  .toColourspace('srgb')    // greyscale / ICC -> sRGB; CMYK WITHOUT a profile is converted naively (1-C)(1-K) like Chromium");
  w("  .ensureAlpha()            // RGBA, 4 bytes/pixel like ImageData");
  w("  .raw()                    // no .resize(): pass FULL resolution; pdq.ts downsamples itself");
  w("// then emulate the canvas premultiply round trip for alpha < 255 (transparent -> 0,0,0)");
  w("```");
  w();
  w("- **Resize:** none. The browser draws 1:1 with smoothing off and pdq.ts does its own 512x512 nearest-neighbour step, so pre-resizing in sharp (any kernel) would diverge from the browser. If memory forces a pre-resize, re-run this harness with that kernel first.");
  w("- **Orientation:** `.rotate()` with no arguments. Skipping it breaks every EXIF-rotated JPEG.");
  w("- **Colour:** `toColourspace('srgb')`; do not use `.greyscale()` or strip profiles. CMYK without an embedded profile must use the naive conversion (sharp's default lcms CMYK profile disagreed by 44 bits); CMYK with a profile uses the normal path (measured 10, the edge of tolerance, one synthetic profile only).");
  w("- **Alpha:** keep alpha, emulate the canvas round trip (see `canvasAlphaRoundTrip`).");
  w("- **Animated:** first frame only (`animated: false`).");
  w();
  w("### Caveats");
  w();
  w("- Fixtures are synthetic. Real photographs have more high-frequency detail and real JPEG quantisation; agreement on real images should be re-checked with a benign public-domain photo set before launch.");
  w("- Text fixtures are blocky pseudo-glyphs, not rendered fonts.");
  w("- One Chromium build on one OS; Safari/Firefox decoders (which survivors may use) are not covered.");
  w("- CMYK with an ICC profile was tested with one synthetic profile (sharp's built-in); real Adobe-inverted or press profiles are untested and may differ.");
  w("- Inputs above 25 MP are rejected by `prepareForPdq` (covered by unit test, not by this report); the crawler cannot fingerprint those.");
  w("- This measures decode agreement only, not match recall against a real hash database.");

  w("## PDQ robustness (same in both pipelines)");
  w();
  w("**This section has no bearing on the GO/NO-GO verdict.** It shows how far PDQ itself moves when an image is recompressed, resized or cropped. Large distances after cropping are PDQ's known weakness and appear identically in the browser pipeline; the last column is the Node-vs-browser distance for the same copy, which is what matters for agreement.");
  w();
  w("| copy | transform | d(orig,copy) browser | d(orig,copy) node-prep | d(orig,copy) node-base | node-vs-browser (prep) |");
  w("|---|---|---|---|---|---|");
  const byName = new Map(rows.map((r) => [r.name, r]));
  const tBrowser: number[] = [], tPrep: number[] = [], tBase: number[] = [];
  for (const f of fixtures.filter((x) => x.originalOf)) {
    const c = byName.get(f.name)!, o = byName.get(f.originalOf!)!;
    if (!c.b || !o.b) continue;
    const db = hammingDistance(o.b.hash, c.b.hash), dp = hammingDistance(o.prep.hash, c.prep.hash), dn = hammingDistance(o.base.hash, c.base.hash);
    tBrowser.push(db); tPrep.push(dp); tBase.push(dn);
    w(`| ${f.name} | ${f.transform} | ${db} | ${dp} | ${dn} | ${c.dPrep} |`);
  }
  w();
  const tb = stats(tBrowser), tp = stats(tPrep), tn = stats(tBase);
  w("| pipeline | max | p95 | mean |");
  w("|---|---|---|---|");
  w(`| browser | ${tb.max} | ${tb.p95} | ${f1(tb.mean)} |`);
  w(`| node-prepared | ${tp.max} | ${tp.p95} | ${f1(tp.mean)} |`);
  w(`| node-baseline | ${tn.max} | ${tn.p95} | ${f1(tn.mean)} |`);
  w();

  // Cross-pipeline matching under transformation: survivor hash (browser, original)
  // against crawler hash (node-prepared, copy) -- the real production comparison.
  const cross: number[] = [];
  for (const f of fixtures.filter((x) => x.originalOf)) {
    const c = byName.get(f.name)!, o = byName.get(f.originalOf!)!;
    if (c.b && o.b) cross.push(hammingDistance(o.b.hash, c.prep.hash));
  }
  const sc = stats(cross);
  w(`Production-shaped check (informational) (survivor browser hash of the original vs crawler node-prepared hash of a transformed copy): max ${sc.max}, p95 ${sc.p95}, mean ${f1(sc.mean)} over ${sc.n} copies (threshold ${PDQ_MATCH_THRESHOLD}).`);
  w();

  const md = L.join("\n") + "\n";
  fs.writeFileSync(path.join(root, "REPORT.md"), md);
  fs.mkdirSync(path.join(root, "out"), { recursive: true });
  fs.writeFileSync(path.join(root, "out", "results.json"), JSON.stringify(rows, null, 1));
  console.log(md.split("## Per image")[0]);
  console.log(md.split("## Which classes")[1]?.split("## Verdict")[0]);
  console.log("## Verdict" + md.split("## Verdict")[1]?.split("## PDQ robustness")[0]);
}
main().catch((e) => { console.error(e); process.exit(1); });
