"""Deterministic synthetic face crops for validation and benchmarking.

Fully synthetic images (no real faces, no real data): a noisy gradient with
a few shapes, "landmarks" generated by applying a seeded similarity
transform to GenD's alignment template, then aligned with the real aligner
so the crops look like what the pipeline produces.
"""

from __future__ import annotations

import cv2
import numpy as np
from PIL import Image

from .align import GEND_TEMPLATE, align_face


def _source_image(rng: np.random.Generator, width: int, height: int) -> np.ndarray:
    """A synthetic BGR photo-like image: smooth gradients + noise + shapes."""
    xs = np.linspace(0, 1, width, dtype=np.float32)
    ys = np.linspace(0, 1, height, dtype=np.float32)
    grid = np.outer(ys, xs)
    base = np.stack([grid * 255, (1 - grid) * 255, (grid * grid) * 255], axis=-1).astype(np.float32)
    base += rng.normal(0, 12, base.shape).astype(np.float32)
    image = np.clip(base, 0, 255).astype(np.uint8)
    for _ in range(4):
        cx = int(rng.integers(0, width))
        cy = int(rng.integers(0, height))
        r = int(rng.integers(width // 20, width // 6))
        color = tuple(int(v) for v in rng.integers(0, 255, 3))
        cv2.circle(image, (cx, cy), r, color, -1)
    return image


def _synthetic_landmarks(rng: np.random.Generator, width: int, height: int) -> np.ndarray:
    """Template landmarks put through a random similarity transform."""
    scale = min(width, height) * float(rng.uniform(0.18, 0.4))
    angle = float(rng.uniform(-25, 25)) * np.pi / 180
    rotation = np.array(
        [[np.cos(angle), -np.sin(angle)], [np.sin(angle), np.cos(angle)]],
        dtype=np.float64,
    )
    centre_offset = np.array(
        [float(rng.uniform(0.3, 0.7)) * width, float(rng.uniform(0.3, 0.7)) * height],
        dtype=np.float64,
    )
    landmarks = (GEND_TEMPLATE.astype(np.float64) - np.array([0.5, 0.6])) @ rotation.T * scale + centre_offset
    return landmarks.astype(np.float32)


def synthetic_aligned_crops(count: int, seed: int = 0, size: int = 480) -> list[Image.Image]:
    """RGB aligned face crops, deterministic for a given seed."""
    rng = np.random.default_rng(seed)
    crops: list[Image.Image] = []
    for _ in range(count):
        image = _source_image(rng, size, size)
        landmarks = _synthetic_landmarks(rng, size, size)
        aligned = align_face(image, landmarks, target_size=None, scale=1.3)
        rgb = cv2.cvtColor(aligned, cv2.COLOR_BGR2RGB)
        crops.append(Image.fromarray(rgb))
    return crops
