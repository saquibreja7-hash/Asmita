/*
 * WP38 part 1: the on-device C2PA Content Credentials reader.
 *
 * The fixture (tests/fixtures/c2pa/ai-fixture.jpg) is a small SYNTHETIC image
 * (a machine-made colour gradient — never a photo of a person) carrying a
 * signed C2PA manifest that states the IPTC AI digital source type
 * (trainedAlgorithmicMedia). It was generated with c2patool, the CAI's own
 * tool from github.com/contentauth/c2pa-rs (MIT OR Apache-2.0), signed with
 * the public C2PA test credentials that ship inside the tool's release
 * archive — see scripts/make-c2pa-fixture.mjs. The committed manifest-store
 * JSON is what c2pa-rs reads back from that exact file, which is the same
 * structure Reader.manifestStore() returns in the browser
 * (@contentauth/c2pa-web wraps the same Rust core).
 */
import { describe, expect, it, vi } from "vitest";
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import {
  C2PA_WASM_PATH,
  C2PA_WORKER_PATH,
  engineConfig,
  summarizeManifestStore,
  type C2paSummary,
} from "@/lib/c2pa-credentials";
import { navGroups } from "@/components/layout/nav-config";

const fixturesDir = join(__dirname, "..", "fixtures", "c2pa");
const fixtureBytes = readFileSync(join(fixturesDir, "ai-fixture.jpg"));
// The dump and the image must stay in sync: this is the digest of the exact
// bytes the committed manifest-store JSON was read from.
const FIXTURE_SHA256 = "c4fbc0736c298b2aa859476c994ef292b2e124abb2bc81490e30ae1641f6ef0c";

/** The C2PA store of a manifest that claims a NON-AI digital source type. */
function storeWithSourceType(sourceType: string): Record<string, unknown> {
  return {
    active_manifest: "urn:test:manifest",
    manifests: {
      "urn:test:manifest": {
        claim_generator: "SomeCamera/2.0",
        assertions: [
          { label: "c2pa.actions.v2", data: { actions: [{ action: "c2pa.created", digitalSourceType: sourceType }] } },
        ],
        signature_info: { common_name: "Some Camera Signer", issuer: "Some Camera CA" },
      },
    },
    validation_state: "Trusted",
  };
}

describe("C2PA fixture (generated by scripts/make-c2pa-fixture.mjs)", () => {
  it("is a valid JPEG whose bytes carry an embedded C2PA manifest", () => {
    expect([...fixtureBytes.subarray(0, 3)]).toEqual([0xff, 0xd8, 0xff]); // JPEG SOI
    expect([...fixtureBytes.subarray(fixtureBytes.length - 2)]).toEqual([0xff, 0xd9]); // JPEG EOI
    expect(fixtureBytes.includes(Buffer.from("c2pa", "ascii"))).toBe(true);
    expect(fixtureBytes.length).toBeLessThan(100 * 1024); // stays small
  });

  it("matches the pinned digest, so the committed manifest store cannot drift from it", () => {
    expect(createHash("sha256").update(fixtureBytes).digest("hex")).toBe(FIXTURE_SHA256);
  });

  it("manifest store is the real c2pa-rs structure with the AI source type and the test signer", () => {
    const store = JSON.parse(readFileSync(join(fixturesDir, "ai-fixture-manifest-store.json"), "utf8"));
    const manifest = store.manifests[store.active_manifest];
    expect(manifest.claim_generator_info[0].name).toBe("AsmitaTestFixtures");
    const action = manifest.assertions.find((a: { label: string }) => a.label === "c2pa.actions.v2");
    expect(action.data.actions[0].digitalSourceType).toBe(
      "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia",
    );
    expect(manifest.signature_info.common_name).toBe("C2PA Signer");
    expect(store.validation_state).toBe("Valid");
  });
});

describe("summarizeManifestStore (what the page shows)", () => {
  const store = JSON.parse(readFileSync(join(fixturesDir, "ai-fixture-manifest-store.json"), "utf8"));

  it("reports the fixture's tool, AI source type, signer and validation, in plain facts", () => {
    const summary: C2paSummary = summarizeManifestStore(store);
    expect(summary.status).toBe("found");
    expect(summary.tool).toBe("AsmitaTestFixtures"); // claim generator info name
    expect(summary.aiUsed).toBe(true); // trainedAlgorithmicMedia
    expect(summary.digitalSourceType).toContain("trainedAlgorithmicMedia");
    expect(summary.signer).toBe("C2PA Signer");
    expect(summary.signatureValidated).toBe(true); // validation_state "Valid"
    expect(summary.validationNote).toBe("signingCredential.untrusted"); // fixed code, never free text
    expect(summary.raw.validationCodes).toContain("claimSignature.validated");
  });

  it("uses the claim_generator string when the generator info list is absent (the classic C.jpg shape)", () => {
    const summary = summarizeManifestStore({
      active_manifest: "x",
      manifests: { x: { claim_generator: "make_test_images/0.12.0 c2pa-rs/0.12.0" } },
    });
    expect(summary.tool).toBe("make_test_images/0.12.0 c2pa-rs/0.12.0");
    expect(summary.aiUsed).toBeUndefined();
  });

  it("does not call an ordinary camera capture AI", () => {
    const summary = summarizeManifestStore(storeWithSourceType("http://cv.iptc.org/newscodes/digitalsourcetype/digitalCapture"));
    expect(summary.status).toBe("found");
    expect(summary.aiUsed).toBe(false);
    expect(summary.digitalSourceType).toContain("digitalCapture");
    expect(summary.signatureValidated).toBe(true);
    expect(summary.validationNote).toBeUndefined(); // no failure codes
  });

  it("marks the composite-with-AI and trainedAlgorithmicData source types as AI too", () => {
    for (const type of [
      "http://cv.iptc.org/newscodes/digitalsourcetype/compositeWithTrainedAlgorithmicMedia",
      "http://c2pa.org/digitalsourcetype/trainedAlgorithmicData",
      "http://cv.iptc.org/newscodes/digitalsourcetype/algorithmicMedia",
    ]) {
      expect(summarizeManifestStore(storeWithSourceType(type)).aiUsed).toBe(true);
    }
  });

  it("finds the AI source type on an ingredient (a parent made with AI)", () => {
    const summary = summarizeManifestStore({
      active_manifest: "x",
      manifests: {
        x: {
          claim_generator: "SomeEditor/1.0",
          ingredients: [{ digital_source_type: "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia" }],
        },
      },
    });
    expect(summary.aiUsed).toBe(true);
  });

  it("reports a store without manifests as 'none' — no verdict, just absence", () => {
    expect(summarizeManifestStore({ active_manifest: null, manifests: {} }).status).toBe("none");
    expect(summarizeManifestStore(null).status).toBe("none");
    expect(summarizeManifestStore(undefined).status).toBe("none");
    expect(summarizeManifestStore("not a store").status).toBe("none");
  });

  it("never throws on malformed manifests", () => {
    for (const bad of [
      { active_manifest: 42, manifests: { a: null } },
      { active_manifest: "a", manifests: { a: { assertions: "no", ingredients: 3 } } },
      { manifests: { a: { claim_generator_info: [null] } } },
    ]) {
      const summary = summarizeManifestStore(bad);
      expect(["none", "found"]).toContain(summary.status);
      expect(summary.aiUsed).toBeUndefined();
    }
  });

  it("signatureValidated is false only for the Invalid state", () => {
    const invalid = summarizeManifestStore({ ...store, validation_state: "Invalid" });
    expect(invalid.signatureValidated).toBe(false);
    const trusted = summarizeManifestStore({ ...store, validation_state: "Trusted" });
    expect(trusted.signatureValidated).toBe(true);
    const unknown = summarizeManifestStore({ ...store, validation_state: null });
    expect(unknown.signatureValidated).toBeUndefined();
  });
});

describe("engine wiring (first-party only)", () => {
  it("points at our own origin's engine files, never a CDN", () => {
    expect(C2PA_WASM_PATH).toBe("/c2pa/c2pa.wasm");
    expect(C2PA_WORKER_PATH).toBe("/c2pa/c2pa_worker.js");
  });

  it("uses the same-origin module worker on https, and the library's inline worker on plain http", () => {
    vi.stubGlobal("location", new URL("https://asmita.test/check-image"));
    try {
      const https = engineConfig();
      expect(https.wasmSrc).toBe("https://asmita.test/c2pa/c2pa.wasm");
      expect(https.workerSrc?.toString()).toBe("https://asmita.test/c2pa/c2pa_worker.js");
      expect(https.workerSrc?.protocol).toBe("https:");
    } finally {
      vi.unstubAllGlobals();
    }
    vi.stubGlobal("location", new URL("http://localhost:3000/check-image"));
    try {
      const http = engineConfig();
      expect(http.wasmSrc).toBe("http://localhost:3000/c2pa/c2pa.wasm");
      expect(http.workerSrc).toBeUndefined(); // the library refuses non-https worker URLs
    } finally {
      vi.unstubAllGlobals();
    }
  });
});

describe("the page the reader runs on", () => {
  it("is entered by a full page load in the nav, so its own CSP is in force (like /talk)", () => {
    const items = navGroups("en").flatMap((group) => group.items);
    expect(items.find((item) => item.href === "/check-image")?.reload).toBe(true);
    expect(items.find((item) => item.href === "/talk")?.reload).toBe(true);
    // Ordinary pages keep soft navigation.
    expect(items.find((item) => item.href === "/start")?.reload).toBeUndefined();
  });
});
