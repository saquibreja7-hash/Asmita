// A corner can sit on part of the scene (an awning, a window), so take the
// commonest light colour along all four edges instead.
function paperColour(data, w, h) {
  const counts = new Map();
  const add = (x, y) => {
    const i = (y * w + x) * 4;
    const key = (data[i] >> 3) + "," + (data[i + 1] >> 3) + "," + (data[i + 2] >> 3);
    const e = counts.get(key) ?? { n: 0, sum: [0, 0, 0] };
    e.n++; for (let c = 0; c < 3; c++) e.sum[c] += data[i + c];
    counts.set(key, e);
  };
  for (let x = 0; x < w; x++) { add(x, 0); add(x, h - 1); }
  for (let y = 0; y < h; y++) { add(0, y); add(w - 1, y); }
  const light = [...counts.values()].filter((e) => e.sum.every((v) => v / e.n > 200));
  const best = (light.length ? light : [...counts.values()]).sort((a, b) => b.n - a.n)[0];
  return best.sum.map((v) => Math.round(v / best.n));
}

const only = process.argv.slice(2);
for (const [name, entry] of Object.entries(MAP)) {
  if (only.length && !only.includes(name)) continue;
  const [file, crop] = Array.isArray(entry) ? entry : [entry];
  // Shown at most 360px wide (760px for who-we-help); twice that covers sharp screens.
  const width = name === "who-we-help" ? 960 : 720;
  const { data, info } = await (crop ? sharp(A + file).extract(crop) : sharp(A + file)).resize({ width, withoutEnlargement: true })
    .removeAlpha().ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const bg = paperColour(data, info.width, info.height);
  for (let i = 0; i < data.length; i += 4) {
    let a = 0;
    for (let c = 0; c < 3; c++) a = Math.max(a, Math.max(0, bg[c] - data[i + c]) / bg[c]);
    if (a < 0.03) { data[i + 3] = 0; continue; }
    for (let c = 0; c < 3; c++) data[i + c] = Math.max(0, Math.min(255, Math.round((data[i + c] - bg[c] * (1 - a)) / a)));
    data[i + 3] = Math.round(a * 255);
  }
  const out = `public/images/illustrations/${name}.webp`;
  const r = await sharp(data, { raw: info }).webp({ quality: 76, alphaQuality: 85 }).toFile(out);
  console.log(out, Math.round(r.size / 1024) + "KB");
}
