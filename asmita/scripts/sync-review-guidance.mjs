// Embeds the review console's per-queue guidance (docs/review-guidance/
// <queueKey>.md, review-console-spec.md WP142) into a generated module,
// src/generated/review-guidance.ts. The app runs on Cloudflare Workers,
// where repo files cannot be read at runtime, so the Markdown is compiled
// in at build time instead; the .md files stay the editable source of truth.
//
// Runs on every install (postinstall), after prisma generate. The generated
// module is not committed (see .gitignore, like the Kysely types beside it),
// so it can never drift from the files: a test (review-guidance.test.ts)
// still compares the two and fails loudly if a session edits the Markdown
// without re-running this script.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const docsDir = join(here, "..", "docs", "review-guidance");
const outDir = join(here, "..", "src", "generated");
const outFile = join(outDir, "review-guidance.ts");

const QUEUE_KEYS = ["links", "fingerprints", "findings", "partners", "lab-reports", "minor-hold"];

const entries = [];
for (const key of QUEUE_KEYS) {
  const file = join(docsDir, `${key}.md`);
  if (!existsSync(file)) {
    console.error(`sync-review-guidance: missing ${file}`);
    process.exit(1);
  }
  entries.push([key, readFileSync(file, "utf8")]);
}

mkdirSync(outDir, { recursive: true });
const body = `// GENERATED by scripts/sync-review-guidance.mjs from docs/review-guidance/*.md.
// Do not edit: edit the Markdown files and re-run the script (or reinstall).
// Raw Markdown only; the renderer (src/lib/review-guidance.ts) sanitises it.

export const REVIEW_GUIDANCE_MARKDOWN: Record<string, string> = {
${entries.map(([key, text]) => `  ${JSON.stringify(key)}: ${JSON.stringify(text)},`).join("\n")}
};
`;

writeFileSync(outFile, body, "utf8");
console.log(`sync-review-guidance: ${entries.length} queues embedded in src/generated/review-guidance.ts`);
